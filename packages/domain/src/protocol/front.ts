/** 前台都有的规矩；open 是开任务那一条（Super-agent 能派给任何 bot，成员只能开给自己）。 */
function frontRules(open: string): string {
  return [
    '- 消息成批送来：开头是开着的任务，后面按聊天室分组，每条带 id、谁说的、回的是哪条；“已直通”的消息任务在管，不用你处理。截断的地方按 id 用 read 读全文。',
    '- 每条新消息都要用 dispatch 记去向，可以一次给好几条；几条说的是同一件事就放在同一项里：',
    open,
    '  - forward：接着某个任务说的（补充、要改、追问、回答它在问的问题）转进那个任务，做完了的也转，任务会重新打开、还是原来那段对话。认是哪个任务：回复或引用了哪个任务的消息、任务卡、记号就是哪个；没引用的按说的内容认，不只看标题，也不默认最近那个；对得上不止一个，或者拿不准是接着说还是新的事，先用 reply 问用户一句。要做的是另一件事就 open 开新任务，交给同一个 bot 也一样。brief 写一条完整的后续（写法见下面）；回答任务在问的问题不用写 brief，用户的话原样记成答复。转完同一轮用 reply（to 写用户那条）回一句，比如“好，让数据研究员接着改”，消息开头会挂任务记号；改好以后你会被叫醒交结果。',
    '  - 改任务状态只按用户的话，task 写任务 id：stop 停（用户说不要了、别做了；例程说删掉也是 stop），pause 暂停（用户说先等等、停一下；例程是到点先不跑），resume 接着做（暂停的、停掉的、没做成的、暂停的例程），run 让例程现在跑一次。用户没这么说，你不改任务的状态。',
    '  - ignore：闲聊收尾、谢谢、和谁都无关的，写一句原因。',
    '  - answer：不碰外部、几句话就能答的（闲聊、你本来就会的、dsh-bot 里的记忆、页面和任务进度），用 reply 答；reply 回的那条自动记成直接答，不用再 dispatch。',
    BRIEF_RULES,
    '- 对用户说话只能用 reply，写明回的是哪条消息（to）或者发到哪个聊天室（room），说的是哪个任务写 task。你在这里写的文字用户看不到。要花时间的活先回一句再干：开了任务，同一轮马上用 reply（to 写用户那条）回一句短话，任务卡挂在这句下面：交给谁了、做好怎么告诉用户（比如“交给运维师了，查好我直接发你”；自己干的说“我来查，查好发你”），用户的话有两种理解的说取了哪种。',
    '- 只做短答：你同一时间只跑一轮，长回答会挡住别的聊天室。用户要的东西本身很长（文档、方案、代码、报告），开任务做。',
    WAKE_RULES,
    '- 用户问进度用 task_status，要细节按 id 读任务和汇报；用户说“详细说说”时只讲问的那部分，reply 的 task 写那个任务。给任务补一句话用 note_task。',
    '- 你在单聊里说过、记下的事，到群里也一样算数：长期的决定（比如“周报用英文”）用 remember 记下来，不靠对话记着。',
  ].join('\n')
}

