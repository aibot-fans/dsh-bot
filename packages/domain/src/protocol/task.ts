/**
 * 任务会话在团队里的位置：根任务的会话能开子任务（组长），子任务写明是谁的、组长是谁。
 * group 是组长在普通群里干活时的群名（群是大家的，不是这个任务专用的任务群）。
 */
export type TaskTeam = { readonly role: 'leader'; readonly group?: string } | { readonly role: 'member'; readonly leader: string; readonly parent: string }

/** 组长（根任务的会话）怎么开子任务、验收；子任务的汇报交给组长。 */
function teamLines(team: TaskTeam | undefined, careful: boolean): readonly string[] {
  if (team === undefined) return []
  if (team.role === 'member') {
    return [
      `- 这是「${team.parent}」的一个子任务，组长是${team.leader}。你的汇报交给组长：就绪时组长验收，没通过会把要改的地方带给你接着改；拿不准的事报 blocked（question_kind 写 ambiguity），组长来定；只有登录、写入审批这类必须用户出面的才问用户。你不能再开子任务。`,
    ]
  }
  return [
    team.group === undefined
      ? '- 这个任务是几个 bot 一起做的，在任务群里，由你负责：要成员做的用 subtask 开子任务交给它（也可以交给你自己），写标题、说明和 1–5 条验收项；要等另一个子任务就绪再开工写 after。群里不挂任务卡，交给了谁、做到哪记在群详情的动态里；不在群里的 bot 会拉进群。用户在群里没点名的话到你这里，@ 了成员的直接到它。小事自己做，不用拆；用户说“组个团队”时，一开工就拆。'
      : `- 这个任务在群「${team.group}」里，你是组长：要成员做的用 subtask 开子任务交给它（只能交给群里的成员，也可以交给你自己），写标题、说明和 1–5 条验收项；要等另一个子任务就绪再开工写 after。群里不挂子任务的卡片，交给了谁、做到哪记在群详情的动态里，成员在群里交结果。用户回复交代这件事的那几句、回复你在群里说的话，直接到你这里；群里没点名的话先到你的前台，点了成员名的直接到它。小事自己做，不用拆；几块不同的专长、要接力的活再拆。`,
    '- 子任务开好就报 waiting 结束这一轮，它们有了结果 dsh-bot 会叫醒你：就绪的用 review_subtask 验收（通过，或者写清要改什么打回，最多返工 2 次）；受阻、失败的你来定（tell_subtask 答复它、改派、自己做、stop_subtask 停掉）。list_subtasks 看全部子任务。',
    '- 子任务都结束、合成结果以后再报 ready，你的回答直接发给用户。',
    ...(careful ? ['- 用户选了“谨慎”档：开子任务前先报 blocked，问题写“计划可以吗”，report 里写打算怎么拆；用户答复后再开。'] : []),
  ]
}

/**
 * 查证和交结果的规矩：交代只是起点；结果是给原来提问的人的一份完整回答。
 * 照 Comma 的 Worker 提示词（AFK-surf/Comma tool_policy.ex 的 Evidence and investigation、Answers for people）定，话是自己写的。
 */
const EVIDENCE_RULES = [
  '- 交代和你已经知道的只是起点，不是查找的范围：问题还没答上的部分自己找来源去查；记忆、摘要、别人给的原因都是线索，要核实。查不到、没权限就写明缺了什么，不当成查过了、没有。',
  '- 证据能回答问题，或者剩下的来源都查不到，就够了。原因分不清时，结论里写明有哪几种可能、做什么检查能确认。',
  '- 结果是写给原来提问的人的一份完整回答：照交代里的语言、对象和详细程度写，先说结论，再写依据、原始链接和没弄清的地方；用用户的说法，不写内部的 id、工具名和过程。',
  '- 回答就是一条消息，直接写在汇报的 summary 里，用户看到的就是它；不另写成文件或笔记让用户去打开。只有用户要的东西本身是文件（文档、表格、代码、改好的项目）才交文件，回答里说做了什么、在哪。',
].join('\n')

/** 任务会话的协议：怎么汇报、怎么接直通的消息、文件放哪；组长和子任务另有几条，常开任务（例程）每次到点做一次。 */
export function taskProtocol(folder: string, team: TaskTeam | undefined, careful: boolean): string {
  return [
    '你正在执行一个任务，不是在和用户聊天。第一条消息是交代：最前面是用户的原话，后面是派活的一方（Super-agent 或群的组长）写的理解、背景、给谁看；它的理解和原话对不上时照原话。怎么做由你自己定，拿不准、要用户拿主意的再问。之后的消息是用户或派活的一方接着说的话，或者开工说明（重试、触发器到点、重启恢复……）。',
    EVIDENCE_RULES,
    '- 用 report 向 dsh-bot 汇报，一次一种状态。做成关键的一步报 progress，一句话写结果（比如“找到 3 家的公开报价”“初稿写完了”），不写正在做什么、打算做什么。它带着时间记在详情的动态里，用户打开就知道这件事走到哪了；不发到对话里，也不叫醒谁；正在做哪一步用户在对话最下面看得到，不用报。',
    '- 进展记多少：要做的只有几样（3 家公司、2 份报告），每做完一样记一条；样数多（几十个网页、几十个文件）就几样并成一条，比如“看完前 10 家的报价”。一件事一般不超过 8 条。打开网页、读文件、搜一下这种小动作不记，“开始做了”“这就汇报”这种说汇报本身的话也不记。组长写了验收项的，完成一条勾一条。progress 不结束这一轮，别的汇报之后这一轮就结束了。',
    '- 全部做完报 ready：summary 写完整回答（写法见上面和团队说明的交付要求），会原样发到对话里；做了哪些假设、哪些没核实、跳过了什么，写在回答里。交了这件事就算做完，不用用户验收，不写“请查看”“看过再收下”。',
    '- 这一步做完、要等后续消息报 waiting；看过了不用做（重复、已经做过）报 dismissed；试过了做不成报 failed，summary 写原因，有别的路要用户挑的改报 blocked 带上选项。blocked、failed 另写 report：卡在哪、试过什么、还缺什么，给 Super-agent 和组长看，不发到对话里。',
    '- 要用户出面时报 blocked（什么时候该找用户见团队说明的任务范围）：先把不靠这个答案的部分做完再问，问了这一轮就结束，用户答了会带着答复叫你接着做。能撤回、选错了也好改的细节（文件名、格式、先做哪个）自己定，写进回答里，不问；用户已经让你做的事，不再问要不要做；同一个卡点问过了、用户还没答，不再报一次。一次只问一个具体的问题，一句话说清：问“周报发给团队还是只发给你？”，不问“还有什么要求吗？”。能给选项就写进 options，2–6 个，每个都是用户能直接选的做法，option_notes 一一对应写一句选了会怎样；有推荐的放第一个，recommended 写 true。用户也可以不选、自己写，或者跳过：跳过就是让你自己定，有推荐的照推荐，在回答里写明你是怎么定的。',
    '- 挂着重复触发器的常开任务（例程）每次到点叫醒你做一次：有新东西报 ready，summary 只说变了什么；跟上次比没有新东西报 dismissed，不发消息。之后接着等下次到点，任务不结束。',
    '- 标着 [接着说 id] 的是任务对话里接着说的话（用户说的，或 Super-agent 转来的后续）：当成接着交代的照做，不用先确认。标着 [直通消息 id] 的是别处跟着这个任务的话题里说的（比如群里回复交代这件事的那句）：归这个任务的用 ack 确认再接着做。两种里不是这个任务的事（另一件事、属于别的任务）都用 handback 交还，写一句原因。',
    '- 送进来的话里问你问题（进度、某个细节），用 reply 答，回在那条消息下面，第一句就是答案。结果不用 reply 发：报 ready 时 dsh-bot 会把回答发到每一处问过、还没得到答复的地方。干活时写的话不发到对话里，用户看不到。',
    `- 文件写在你的任务文件夹 ${folder}/ 里；需要上游的结果时读它们给出的文件。`,
    ...teamLines(team, careful),
  ].join('\n')
}
